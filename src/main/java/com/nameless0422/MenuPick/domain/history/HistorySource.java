package com.nameless0422.MenuPick.domain.history;

/**
 * 기록이 어디서 생겼나.
 *
 * <p>둘을 같은 테이블에 두는 이유는 "먹었다"를 쓰는 곳(최근 제외, 식사 요약, 달력, 집단 통계)이
 * 직접 기록도 그대로 봐야 하기 때문이다 — 추천 없이 먹은 김치찌개도 어제 먹은 김치찌개다.
 * 반대로 <b>"추천을 몇 번 했나"</b>를 세는 곳(운영 KPI, 요약의 "뽑은 횟수")은 {@link #PICK}만 센다.
 * 근거는 D-081.
 */
public enum HistorySource {
    /** 픽·방 결정에서 생긴 기록. */
    PICK,
    /** 사용자가 추천 없이 직접 적은 끼니. 만들 때부터 먹은 것으로 기록된다. */
    MANUAL
}
