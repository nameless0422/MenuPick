package com.nameless0422.MenuPick.domain.trend;

/**
 * 무엇을 기준으로 세는가.
 *
 * <h2>왜 둘로 나뉘어 있고, 왜 태그는 없는가</h2>
 *
 * <p>집단 통계는 <b>사용자들이 같은 말을 써야</b> 성립한다. 세 축의 사정이 전부 다르다.
 *
 * <ul>
 *   <li>{@link #CATEGORY} — 화면이 고정 목록(8개)에서만 고르게 하고
 *       ({@code frontend/src/constants.ts}의 {@code CATEGORY_PRESETS}), 가입할 때 깔리는 기본
 *       메뉴 22개에 이미 붙어 있다(V10). 신규 사용자도 첫 픽부터 집계에 기여한다.</li>
 *   <li>{@link #MENU} — 이름이 사용자별 자유 텍스트다. 다만 기본 메뉴 22개는 모든 계정에
 *       <b>같은 문자열</b>로 들어가므로 그 22개에 한해서는 사용자 간에 맞아떨어진다. 직접 만든
 *       공개 집계는 {@link TrendVocabulary}의 22개 이름만 허용한다. 같은 문자열로 이름을 바꾼
 *       사용자 메뉴도 구분할 seed 표식은 없으므로, 이는 원본 행의 출처 증명이 아니라 닫힌 어휘 정책이다.</li>
 *   <li>태그 — 넣지 않는다. 기본 태그를 깔아주는 곳이 아예 없어(V10은 메뉴·카테고리만 넣는다)
 *       공통 어휘가 0이다. "혼밥"·"혼자"·"솔로"가 제각각 만들어져 집계하면 1명짜리만 흩어진다.
 *       기본 태그를 도입한다면 그때 이 enum에 한 줄 더하면 된다.</li>
 * </ul>
 *
 * <p>DB에는 이름 문자열로 저장한다({@code VARCHAR(20)}). ordinal로 저장하면 나중에 상수를
 * 끼워 넣는 순간 이미 쌓인 행의 의미가 통째로 바뀐다.
 */
public enum TrendDimension {

    /** 한식·중식 같은 카테고리. 지금 바로 의미 있는 숫자가 나오는 유일한 축. */
    CATEGORY,

    /** 메뉴 이름. 기본 메뉴 22개만 사실상 집계된다 — 근거는 위 주석. */
    MENU
}
