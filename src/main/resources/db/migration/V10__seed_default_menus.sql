-- =============================================
-- 기존 계정에 기본 메뉴 백필
--
-- 가입 직후 메뉴 목록은 비어 있고, 이 앱에서 사용자가 가장 먼저 하려는 일(픽)은 메뉴가 하나도
-- 없으면 아예 동작하지 않는다. 앞으로 가입하는 계정은 애플리케이션이 넣어 준다
-- (DefaultMenuProvisioner — 메일 인증을 통과하는 시점). 이 마이그레이션은 그 코드가 생기기
-- 전에 이미 만들어진 계정을 한 번 따라잡게 한다.
--
-- 목록은 DefaultMenus.PRESETS의 **이 시점 스냅샷**이다. 자바 쪽 목록을 나중에 고쳐도 이 파일은
-- 따라가지 않는다 — 마이그레이션 파일은 불변이고(MigrationImmutabilityTest), 이미 자기 목록을
-- 손질한 사용자의 데이터를 나중에 맞춰 넣을 이유도 없다. 두 목록이 갈라지는 것은 의도한 것이다.
--
-- 대상: 살아 있고(deleted_at IS NULL) 메일 인증까지 끝났으며(email_verified = 1) 메뉴가 한 건도
-- 없는 계정.
--   - 미인증 계정을 빼는 이유: 그 행은 로그인할 수 없고 같은 주소로 다시 가입하면 덮어써지는
--     임시 상태다. 끝내 인증하지 않을 주소마다 메뉴 22행이 남는다. 인증을 통과하면 그때
--     애플리케이션이 넣는다.
--   - 탈퇴 계정을 빼는 이유: 유예기간 안에 돌아오면 쓰던 메뉴가 그대로 살아나고, 유예가 지나면
--     하드 삭제 배치가 행을 지운다. 어느 쪽이든 지금 채워 넣을 자리가 아니다.
--   - "메뉴가 한 건도 없는"에는 soft delete된 메뉴도 포함해서 센다. 메뉴를 만들었다가 전부 지운
--     사용자에게 앱이 임의로 목록을 채워 주는 동작은 하지 않는다.
--
-- 이 메뉴들은 평범한 사용자 소유 행으로 들어간다 — 가중치 1, 제외 아님, 시드임을 표시하는
-- 플래그 없음. 플래그가 있으면 "기본 메뉴는 못 지운다"거나 "업데이트 때 다시 채운다" 같은
-- 규칙이 따라붙기 마련인데, 남의 개인 목록을 앱이 나중에 손대는 동작은 이 앱에 없어야 한다.
--
-- 원자성: MySQL은 DDL이 트랜잭션이 아니고 flyway-mysql도 롤백을 제공하지 않는다(V5 주석 참고).
-- 다만 여기서 쓰는 DDL은 임시 테이블뿐이라 암묵적 커밋을 일으키지 않으며(CREATE/DROP TEMPORARY
-- TABLE은 MySQL의 암묵적 커밋 예외다), 두 INSERT는 순수 DML이다. 중간에 실패하면 menus에는
-- 들어갔는데 menu_categories가 비어 있는 상태가 남을 수 있다 — 카테고리 없는 메뉴는 앱에서
-- 정상 상태이므로(필터에 안 걸릴 뿐) 사용자에게 깨진 화면이 보이지는 않는다.
-- =============================================

-- ---------------------------------------------------------------------
-- 1. 시드 목록. 값 목록을 두 INSERT가 함께 쓰므로 임시 테이블에 담는다.
--
--    콜레이션을 menus.name과 같은 utf8mb4_0900_ai_ci로 명시한다(V7). 임시 테이블은 스키마
--    기본값을 따르므로 지금은 명시하지 않아도 같지만, 아래 3번의 JOIN이 name으로 붙기 때문에
--    콜레이션이 어긋나면 "Illegal mix of collations"로 마이그레이션이 통째로 실패한다.
--    그 실패가 스키마 기본값 변경에 딸려 오는 것보다 여기 적어 두는 편이 낫다.
-- ---------------------------------------------------------------------
CREATE TEMPORARY TABLE tmp_default_menu_seed (
    name     VARCHAR(100) NOT NULL,
    category VARCHAR(20)  NOT NULL,
    PRIMARY KEY (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

