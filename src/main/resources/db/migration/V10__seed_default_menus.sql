-- ---------------------------------------------------------------------
-- 2. 대상 계정을 먼저 고정한다.
--
--    "메뉴가 없는 계정"이라는 조건은 아래 INSERT가 끝나는 순간 거짓이 되므로, 3번에서 다시
--    평가할 수 없다. 그래서 대상을 미리 잡아 둔다. 이 목록이 3번에서 "방금 넣은 행"을
--    가려내는 근거이기도 하다 — 대상 계정은 메뉴가 0건이었으므로, 2번 이후 그 계정의 메뉴는
--    전부 이 마이그레이션이 넣은 것이다.
-- ---------------------------------------------------------------------
CREATE TEMPORARY TABLE tmp_default_menu_target (
    user_id BIGINT NOT NULL,
    PRIMARY KEY (user_id)
) ENGINE=InnoDB;

INSERT INTO tmp_default_menu_target (user_id)
SELECT u.id
FROM users u
WHERE u.deleted_at IS NULL
  AND u.email_verified = 1
  AND NOT EXISTS (SELECT 1 FROM menus m WHERE m.user_id = u.id);

-- ---------------------------------------------------------------------
-- 3. 메뉴 본체. weight/is_excluded는 기본값과 같은 값을 명시해 둔다 — 읽는 사람이 스키마를
--    찾아가지 않아도 "가중치 1, 제외 아님"이 보이게. version(V9)·created_at·updated_at은
--    컬럼 기본값에 맡긴다.
-- ---------------------------------------------------------------------
INSERT INTO menus (user_id, name, weight, is_excluded)
SELECT t.user_id, s.name, 1, 0
FROM tmp_default_menu_target t
CROSS JOIN tmp_default_menu_seed s;

-- ---------------------------------------------------------------------
-- 4. 카테고리. 3번이 만든 행의 id를 알 수 없으니 (대상 계정 × 시드 이름)으로 되찾는다.
--    대상 계정은 2번 시점에 메뉴가 0건이었고 시드 이름은 유일하므로, 이 조인은 방금 넣은
--    행에만 정확히 하나씩 붙는다.
-- ---------------------------------------------------------------------
INSERT INTO menu_categories (menu_id, category)
SELECT m.id, s.category
FROM menus m
JOIN tmp_default_menu_target t ON t.user_id = m.user_id
JOIN tmp_default_menu_seed s ON s.name = m.name;

DROP TEMPORARY TABLE tmp_default_menu_target;
DROP TEMPORARY TABLE tmp_default_menu_seed;
