/**
 * 별점·선호도 버튼의 상태를 클래스와 {@code aria-pressed}에 한 번에 준다.
 *
 * <p>{@link chipToggle}과 같은 문제, 같은 해법이다. 이 버튼들은 지금 값이 몇인지를
 * 채워진 별의 색으로만 보여준다(.star.on). 색은 보조기술로 전달되지 않으므로
 * aria-pressed가 없으면 스크린리더에는 "선호도 1 버튼 … 선호도 5 버튼" 다섯 개가
 * 상태 없이 읽히고, 지금이 3인지 5인지 알 방법이 없다. 눌러도 변화가 통지되지 않아
 * 값을 확인할 수단 자체가 없다.
 *
 * <p>두 속성을 호출부에서 따로 쓰지 않고 여기서 함께 만드는 이유도 같다 — 클래스 조건만
 * 손대고 aria를 빼먹으면 화면은 멀쩡한데 읽히는 상태만 틀리는, 눈으로는 안 보이는 버그가 된다.
 *
 * <p>별 하나하나가 "이 값 이하가 선택됨"을 뜻하므로, 선호도 3이면 1·2·3이 눌린 상태다.
 * 채워진 별이 셋이라는 화면상의 사실과 정확히 같은 정보다.
 *
 * @param on 이 별이 채워진 상태인지 (value <= 현재값)
 */
export function starToggle(on: boolean) {
  return {
    className: on ? "star on" : "star",
    "aria-pressed": on,
  };
}
